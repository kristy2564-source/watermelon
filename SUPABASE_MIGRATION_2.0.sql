--  用法：复制全部内容到 Supabase 项目 → SQL Editor → New query → Run
--  说明：本脚本是**幂等**的，可重复执行，不会丢历史数据
--  影响：
--    - 1.0 老用户：旧纪录自动归入「全服榜(classic)」
--    - 2.0 新功能：排行榜双模式（classic / power）
