-- ---------- 路径 A：1.0 老表，升级到 2.0 ----------
-- 加 mode 列（不存在才加），默认 'classic'，旧数据自动归入全服榜
alter table score
  add column if not exists mode text not null default 'classic';

-- 删除旧的 name 唯一约束（如果有），换成 (name, mode) 联合唯一
-- 同一玩家在两榜上可以有同名但不同模式的两条记录
alter table score
  drop constraint if exists score_name_key;

create unique index if not exists score_name_mode_key
  on score(name, mode);

